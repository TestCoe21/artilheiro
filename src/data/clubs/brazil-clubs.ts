export function getBrazilianClubById(id: string): Club | undefined {
  return BRAZIL_CLUBS.find((club) => club.id === id);
}

export function getSelectableBrazilianClubs(): Club[] {
  return BRAZIL_CLUBS.filter((club) => club.selectable);
}

export function getBrazilianClubsByDivision(
  division: "serie-a" | "serie-b",
): Club[] {
  return BRAZIL_CLUBS.filter((club) => club.division === division);
}

export function getBrazilianClubsByState(
  state: string,
): Club[] {
  return BRAZIL_CLUBS.filter((club) => club.state === state);
}

export function getBrazilianClubsByRegionalCompetition(
  regional: "nordeste" | "sul-sudeste" | "verde",
): Club[] {
  return BRAZIL_CLUBS.filter(
    (club) => club.regionalChampionship === regional,
  );
}
